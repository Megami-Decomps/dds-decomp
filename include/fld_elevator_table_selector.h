#ifndef FLD_ELEVATOR_TABLE_SELECTOR_H
#define FLD_ELEVATOR_TABLE_SELECTOR_H

#include "common.h"

/* Selectors 2-7 read floor values, 8-13 read block IDs, and 14 returns the
 * selected floor's reverse index; unrecognized selectors return zero. */
typedef enum FldElevatorTableSelector {
    FLD_ELEVATOR_TABLE_SELECTOR_FLOOR_COUNT = 0,
    FLD_ELEVATOR_TABLE_SELECTOR_SOUND = 1,
    FLD_ELEVATOR_TABLE_SELECTOR_FLOOR_0 = 2,
    FLD_ELEVATOR_TABLE_SELECTOR_FLOOR_1 = 3,
    FLD_ELEVATOR_TABLE_SELECTOR_FLOOR_2 = 4,
    FLD_ELEVATOR_TABLE_SELECTOR_FLOOR_3 = 5,
    FLD_ELEVATOR_TABLE_SELECTOR_FLOOR_4 = 6,
    FLD_ELEVATOR_TABLE_SELECTOR_FLOOR_5 = 7,
    FLD_ELEVATOR_TABLE_SELECTOR_BLOCK_0 = 8,
    FLD_ELEVATOR_TABLE_SELECTOR_BLOCK_1 = 9,
    FLD_ELEVATOR_TABLE_SELECTOR_BLOCK_2 = 10,
    FLD_ELEVATOR_TABLE_SELECTOR_BLOCK_3 = 11,
    FLD_ELEVATOR_TABLE_SELECTOR_BLOCK_4 = 12,
    FLD_ELEVATOR_TABLE_SELECTOR_BLOCK_5 = 13,
    FLD_ELEVATOR_TABLE_SELECTOR_REVERSED_SELECTED_FLOOR_INDEX = 14,
} FldElevatorTableSelector;

s32 fldDoor_GetElvTbl(FldElevatorTableSelector selector);

#endif /* FLD_ELEVATOR_TABLE_SELECTOR_H */
