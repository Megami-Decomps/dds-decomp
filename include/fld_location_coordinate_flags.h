#ifndef FLD_LOCATION_COORDINATE_FLAGS_H
#define FLD_LOCATION_COORDINATE_FLAGS_H

#include "common.h"

/* Signed flag word at +0x06 in a location-coordinate record; zero on a miss. */
typedef s16 FldLocationCoordinateFlags;

/* Names for masks whose effects are directly visible at their consumers. */
enum FldLocationCoordinateFlag {
    FLD_LOCATION_COORDINATE_FLAG_FIELD_COMMAND_ENABLED = 0x0001,
    FLD_LOCATION_COORDINATE_FLAG_SPAWN_SECONDARY_SCENE_OBJECT = 0x0004,
    FLD_LOCATION_COORDINATE_FLAG_CAMERA_COLOR_SETTING = 0x0008,
    /* DDS1 shares this bit with the camera-color setting. */
    FLD_LOCATION_COORDINATE_FLAG_INITIALIZE_MENU_RESOURCES_DDS1 = 0x0008,
    FLD_LOCATION_COORDINATE_FLAG_LOAD_KF2_ROOM_CHUNK = 0x0010,
    FLD_LOCATION_COORDINATE_FLAG_PLAYER_MODEL_VARIANT_2 = 0x0020,
    FLD_LOCATION_COORDINATE_FLAG_FIELD_EFFECT_TEXTURES = 0x0040,
    FLD_LOCATION_COORDINATE_FLAG_CAMERA_TILT = 0x0100,
    FLD_LOCATION_COORDINATE_FLAG_LOAD_RESOURCE_INDEX_0 = 0x0200,
    FLD_LOCATION_COORDINATE_FLAG_LOAD_RESOURCE_INDEX_1 = 0x0400,
    FLD_LOCATION_COORDINATE_FLAG_INITIALIZE_MENU_RESOURCES_DDS2 = 0x0800
};

FldLocationCoordinateFlags fldGetLocationCoordinateFlags(s32 area, s32 locationIndex);

#endif
