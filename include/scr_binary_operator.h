#ifndef SCR_BINARY_OPERATOR_H
#define SCR_BINARY_OPERATOR_H

#include "common.h"

/* Operation selector shared by the script VM's integer and float dispatch. */
typedef s32 ScrBinaryOperator;
enum {
    SCR_BINARY_OPERATOR_ADD = 0,
    SCR_BINARY_OPERATOR_SUBTRACT = 1,
    SCR_BINARY_OPERATOR_MULTIPLY = 2,
    SCR_BINARY_OPERATOR_DIVIDE = 3,
    SCR_BINARY_OPERATOR_LOGICAL_OR = 4,
    SCR_BINARY_OPERATOR_LOGICAL_AND = 5,
    SCR_BINARY_OPERATOR_EQUAL = 6,
    SCR_BINARY_OPERATOR_NOT_EQUAL = 7,
    SCR_BINARY_OPERATOR_LESS_THAN = 8,
    SCR_BINARY_OPERATOR_GREATER_THAN = 9,
    SCR_BINARY_OPERATOR_LESS_OR_EQUAL = 10,
    SCR_BINARY_OPERATOR_GREATER_OR_EQUAL = 11
};

#endif /* SCR_BINARY_OPERATOR_H */
