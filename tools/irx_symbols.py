#!/usr/bin/env python3
"""Export the IRX module symbols from their IDBs into config/irx/<name>/symbol_addrs.txt.

    python tools/irx_symbols.py            # every module
    python tools/irx_symbols.py SDFIOP

Read-only on the IDB side. The files it writes drive tools/irx_split.py.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import irx_config  # noqa: E402
IDA_SCRIPTS = Path(
    os.environ.get("IDA_SKILL_SCRIPTS", Path.home() / ".claude/skills/ida-instances/scripts")
)

PAYLOAD = r'''
def export():
    import json
    import ida_bytes, ida_funcs, ida_segment, idautils, idc

    KEEP = (".text", ".rodata", ".data", ".sdata", ".sbss", ".bss")

    def seg(ea):
        s = ida_segment.getseg(ea)
        return ida_segment.get_segm_name(s) if s else None

    rows = []
    funcs = set()
    for ea in idautils.Functions():
        if seg(ea) != ".text":
            continue
        funcs.add(ea)
        f = ida_funcs.get_func(ea)
        rows.append(["F", ea, idc.get_func_name(ea), f.end_ea - ea])
    for ea, name in idautils.Names():
        if ea in funcs or seg(ea) not in KEEP:
            continue
        rows.append(["D", ea, name, ida_bytes.get_item_size(ea)])
    rows.sort(key=lambda r: r[1])
    return json.dumps(rows)

RESULT = export()
'''

# IDA's own placeholder names carry no information; the splitter invents its own.
PLACEHOLDER_PREFIXES = (
    "sub_", "nullsub_", "loc_", "locret_", "def_", "unk_", "byte_", "word_",
    "dword_", "qword_", "asc_", "algn_", "jpt_", "jtbl_", "off_", "stru_",
)


def collect(instance: str, ports: str | None) -> list:
    sys.path.insert(0, str(IDA_SCRIPTS))
    import ida

    instances = ida.get_instances(
        ida.parse_ports(ports or ida.DEFAULT_PORTS), refresh=False)
    port = ida.resolve_target(instance, instances)
    out = ida.call_tool(port, "py_eval", {"code": PAYLOAD, "new_locals": True})
    if out.get("stderr"):
        raise SystemExit(f"IDAPython failed:\n{out['stderr']}")
    blob = ida.call_tool(port, "py_eval", {"code": "RESULT", "new_locals": False})
    return json.loads(blob["result"])


def render(rows: list) -> str:
    """splat's symbol_addrs format, the same one config/dds1 uses.

    A function IDA has found but not named still has to appear, because its
    bounds are what gives tools/irx_split.py one chunk per function; it comes
    across as func_<address> until the IDB learns its name. Unnamed data is
    left out, since the splitter names what it finds there itself.
    """
    lines = ["// Generated by tools/irx_symbols.py from the IDB; do not hand-edit."]
    for kind, addr, name, size in rows:
        if name.startswith(PLACEHOLDER_PREFIXES):
            if kind != "F":
                continue
            name = f"func_{addr:08X}"
        attrs = ["type:func"] if kind == "F" else []
        if size:
            attrs.append(f"size:0x{size:X}")
        suffix = f" // {' '.join(attrs)}" if attrs else ""
        lines.append(f"{name} = 0x{addr:08X};{suffix}")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("modules", nargs="*")
    ap.add_argument("--ports", default=None,
                    help="port list or range; default is the ida.py default")
    args = ap.parse_args()
    for module in args.modules or irx_config.modules():
        cfg = irx_config.load(module)
        # Several builds of Sony's sound modules are often open at once, so a
        # config can name its IDB by path instead of by module name.
        rows = collect(cfg.get("idb", cfg["name"]), args.ports)
        path = irx_config.path(cfg, "symbols")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(rows))
        print(f"{path.relative_to(ROOT)}: {len(rows)} symbols")


if __name__ == "__main__":
    main()
