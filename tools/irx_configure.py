#!/usr/bin/env python3
"""Write build-irx.ninja, which rebuilds the IRX modules and checks them.

    python tools/irx_configure.py && ninja -f build-irx.ninja

Separate from configure.py: these are IOP modules with their own compiler,
linker script and container, and nothing they do touches the main ELF build.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import ninja_syntax

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import irx_config  # noqa: E402

TOOLS = Path("tools")
BIN = TOOLS / "bin"
IOPGCC = TOOLS / "compilers" / "iop-gcc2.8.1"
IOP_DIR = IOPGCC / "lib" / "gcc-lib" / "mipsel-scei-elfl" / "2.8.1"
CPP = IOP_DIR / "cpp"
CC1 = IOP_DIR / "cc1"
IOP_AS = IOP_DIR / "as"
LD = BIN / "mips-ps2-decompals-ld"

# What the iop-gcc driver's specs pass to cpp for this target, plus ASM_ROOT.
CPP_DEFINES = [
    "-D__GNUC__=2", "-D__GNUC_MINOR__=8", "-Dmips", "-DMIPSEL", "-D_MIPSEL",
    "-D__mips__", "-D__MIPSEL__", "-D__mips", "-D__MIPSEL", "-D__R3000__",
    "-D__LANGUAGE_C", "-D_LANGUAGE_C", "-DLANGUAGE_C", "-D__OPTIMIZE__",
    "-DASM_ROOT=\\\"asm/irx/\\\"",
]

LINKER_SCRIPT = """/* Generated by tools/irx_configure.py; do not edit.
 *
 * The module is linked at 0 and the loader relocates it. _gp sits 0x7ff0 past
 * the end of .data, where .sdata would start, which is where the .iopmod of
 * every retail module puts it.
 */
OUTPUT_FORMAT("elf32-littlemips")
OUTPUT_ARCH(mips)
ENTRY(%(entry)s)
SECTIONS
{
    . = 0x00000000;
    .text   ALIGN(16) : { *(.text) *(.text.*) }
    .rodata ALIGN(16) : { *(.rodata) *(.rodata.*) }
    .data   ALIGN(16) : { *(.data) *(.data.*) }
    _gp = . + 0x7ff0;
    .sdata  ALIGN(16) : { *(.sdata) *(.sdata.*) }
    .sbss   ALIGN(4) (NOLOAD) : { *(.sbss) *(.sbss.*) *(.scommon) }
    .bss    ALIGN(16) (NOLOAD) : { *(.bss) *(.bss.*) *(COMMON) }
    /DISCARD/ : {
        *(.pdr) *(.mdebug*) *(.comment) *(.gnu.attributes) *(.reginfo)
        *(.note*) *(.options)
    }
}
"""


def i386(root: Path) -> str:
    """The pinned 32-bit loader the EE compilers already run under."""
    libdir = root / "tools" / "glibc32"
    if (libdir / "libc.so.6").exists():
        return f"tools/glibc32/ld-linux.so.2 --library-path tools/glibc32 "
    return ""


INCLUDE_ASM_LINE = re.compile(r'^\s*INCLUDE_ASM\("[^"]+",\s*([A-Za-z_.][\w.]*)\s*\)')


def chunks(cfg: dict) -> list[str]:
    """The module's .text chunks in link order.

    Once the C file exists its INCLUDE_ASM lines are the order, since a
    decompiled function replaces its line in place. Before that, the order
    tools/irx_split.py wrote bootstraps it.
    """
    src = irx_config.path(cfg, "src")
    if src.exists():
        return [m[1] for m in (INCLUDE_ASM_LINE.match(l) for l in src.read_text().splitlines()) if m]
    order = irx_config.path(cfg, "build") / "text_order.txt"
    if not order.exists():
        raise SystemExit(f"{order} is missing; run tools/irx_split.py first")
    return [l.strip() for l in order.read_text().splitlines()
            if l.strip() and not l.startswith("#")]


def write_ninja(args) -> None:
    out = ROOT / "build-irx.ninja"
    with out.open("w") as fh:
        n = ninja_syntax.Writer(fh, width=120)
        n.comment("Generated by tools/irx_configure.py; do not edit.")
        n.variable("ninja_required_version", "1.10")
        n.newline()
        run = i386(ROOT)
        n.rule("iopas", f"{run}{IOP_AS} -EL -G 0 -I. -o $out $in", description="iop-as $in")
        n.rule("iopcc",
               f"{run}{CPP} -lang-c $cppflags -Iinclude/irx $in $out.i && "
               f"{run}{CC1} -quiet -O2 -G 0 $cflags $out.i -o $out.s && "
               f"{run}{IOP_AS} -EL -G 0 -I. -o $out $out.s",
               description="iop-gcc $in")
        n.variable("cppflags", " ".join(CPP_DEFINES))
        n.variable("cflags", "")
        n.rule("link", f"{LD} -EL -T $script --emit-relocs -o $out $in",
               description="link $out")
        n.rule("pack",
               f"$python {TOOLS}/irx.py pack $in -o $out --name $name --version $version",
               description="pack $out")
        n.rule("verify", f"$python {TOOLS}/irx_verify.py $in $orig && touch $out",
               description="verify $orig")
        n.rule("textlist", f"$python {TOOLS}/irx_configure.py --textlist $module",
               description="text list $module", generator=True)
        n.rule("script", f"$python {TOOLS}/irx_configure.py --script $module",
               description="linker script $module", generator=True)
        n.rule("configure", f"$python {TOOLS}/irx_configure.py",
               description="irx_configure.py", generator=True)
        n.variable("python", sys.executable)
        n.newline()

        targets = []
        for module in irx_config.modules():
            cfg = irx_config.load(module)
            asm = Path(cfg["paths"]["asm"])
            b = Path(cfg["paths"]["build"])
            src = Path(cfg["paths"]["src"])
            script = b / "link.ld"
            deps = [str(asm / "text" / f"{c}.s") for c in chunks(cfg)]
            n.build(str(script), "script", [], variables={"module": module})

            objs = []
            if (ROOT / src).exists():
                # The generated header has to be a dependency, or a change to
                # it leaves text.o stale and the verify passes on code that no
                # longer compiles.
                headers = ["include/irx/irx.h", "include/irx/iop.h"]
                generated = Path("include") / "irx" / f"{module}.h"
                if (ROOT / generated).exists():
                    headers.append(str(generated))
                n.build(str(b / "text.o"), "iopcc", [str(src)],
                        implicit=deps + headers)
            else:
                text_s = b / "text.s"
                n.build(str(text_s), "textlist", [], variables={"module": module})
                n.build(str(b / "text.o"), "iopas", [str(text_s)], implicit=deps)
            objs.append(str(b / "text.o"))
            for part in ("rodata", "data", "bss"):
                part_src = asm / f"{part}.s"
                if (ROOT / part_src).exists() and (ROOT / part_src).stat().st_size:
                    n.build(str(b / f"{part}.o"), "iopas", [str(part_src)])
                    objs.append(str(b / f"{part}.o"))

            elf = b / f"{module}.elf"
            n.build(str(elf), "link", objs, implicit=[str(script)],
                    variables={"script": str(script)})
            built = b.parent / f"{module}.IRX"
            n.build(str(built), "pack", [str(elf)],
                    variables={"name": cfg["module"]["name"],
                               "version": str(cfg["module"]["version"])})
            stamp = b.parent / f"{module}.ok"
            n.build(str(stamp), "verify", [str(built)],
                    implicit=[cfg["paths"]["target"], str(TOOLS / "irx_verify.py")],
                    variables={"orig": cfg["paths"]["target"]})
            targets.append(str(stamp))
            n.newline()

        n.build("all", "phony", targets)
        n.default("all")
        n.build("build-irx.ninja", "configure",
                implicit=[str(TOOLS / "irx_configure.py")]
                + [f"config/irx/{m}/{m}.yaml" for m in irx_config.modules()])
    print(f"wrote {out}")


def write_textlist(module: str) -> None:
    """One .s that includes the module's .text chunks, before any C exists."""
    cfg = irx_config.load(module)
    asm = cfg["paths"]["asm"]
    lines = ["# Generated by tools/irx_configure.py; do not edit.",
             "    .set noat", "    .set noreorder", "    .section .text"]
    lines += [f'    .include "{asm}/text/{c}.s"' for c in chunks(cfg)]
    path = irx_config.path(cfg, "build") / "text.s"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def write_c(module: str) -> None:
    """The module's C file: every .text chunk as INCLUDE_ASM, in link order.

    Written once. Decompiling a function means replacing its INCLUDE_ASM line
    with the C body, which keeps the chunk in the same place in .text.
    """
    cfg = irx_config.load(module)
    path = irx_config.path(cfg, "src")
    if path.exists():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ['#include "irx.h"', ""]
    lines += [f'INCLUDE_ASM("{module}", {c});' for c in chunks(cfg)]
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path.relative_to(ROOT)}")


def write_script(module: str) -> None:
    cfg = irx_config.load(module)
    path = irx_config.path(cfg, "build") / "link.ld"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(LINKER_SCRIPT % {"entry": cfg["module"]["entry"]})


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--textlist", metavar="MODULE")
    ap.add_argument("--script", metavar="MODULE")
    args = ap.parse_args()
    if args.textlist:
        write_textlist(args.textlist)
    elif args.script:
        write_script(args.script)
    else:
        for module in irx_config.modules():
            write_script(module)
            write_c(module)
        write_ninja(args)


if __name__ == "__main__":
    main()
